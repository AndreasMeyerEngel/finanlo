const today = new Date();

function dateInMonth(monthOffset: number, day: number): string {
  return toIsoDate(clampDay(today.getFullYear(), today.getMonth() + monthOffset, day));
}

function monthKey(monthOffset: number): string {
  return getMonthKey(new Date(today.getFullYear(), today.getMonth() + monthOffset, 1));
}

